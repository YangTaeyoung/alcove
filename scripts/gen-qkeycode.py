#!/usr/bin/env python3
"""Generate Swift QKeyCode enum from QEMU's qapi/ui.json (pinned tag).
The numeric value of each case is its ordinal in the qapi enum, which is what
QEMU uses internally (qemu_input_event_send_key_qcode takes a QKeyCode int).
Usage: scripts/gen-qkeycode.py build/qemu-src/qapi/ui.json > AlcoveKit/Sources/AlcoveDisplayProtocol/QKeyCode.swift
"""
import json, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
# qapi json is not strict JSON (single quotes, comments). Extract the QKeyCode enum block.
m = re.search(r"\{\s*'enum'\s*:\s*'QKeyCode'.*?'data'\s*:\s*\[(.*?)\]", src, re.S)
if not m:
    sys.exit("QKeyCode enum not found")
names = re.findall(r"'([a-z0-9_]+)'", m.group(1))
def swift_name(n):
    n = n.replace("_", " ")
    parts = n.split()
    s = parts[0] + "".join(p.capitalize() for p in parts[1:])
    if s[0].isdigit():
        s = "k" + s
    return s
print("// Generated by scripts/gen-qkeycode.py from QEMU qapi/ui.json. Do not edit.")
print("// Raw values are the qapi enum ordinals used by qemu_input_event_send_key_qcode().")
print("public enum QKeyCode: Int, Codable, CaseIterable, Sendable {")
for i, n in enumerate(names):
    print(f"    case {swift_name(n)} = {i}  // {n}")
print("}")
print()
print("extension QKeyCode {")
print("    /// The qapi name of this key code, e.g. \"shift_r\".")
print("    public var qapiName: String {")
print("        switch self {")
for n in names:
    print(f"        case .{swift_name(n)}: return \"{n}\"")
print("        }")
print("    }")
print("}")
